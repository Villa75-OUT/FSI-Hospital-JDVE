    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    String curp = "ausl120130a";
        
        String query = "SELECT fecha_hora, nvl_glucosa FROM ("
             + "  SELECT CONCAT(fecha, ' ', hora) AS fecha_hora, nvl_glucosa, fecha, hora "
             + "  FROM mediciones "
             + "  WHERE pacientes_curp = '" + curp + "' "
             + "  ORDER BY fecha DESC, hora DESC "
             + "  LIMIT 15"
             + ") AS ultimas "
             + "ORDER BY fecha ASC, hora ASC;";

datos = cnx.consultar(query);

series.clear();
series.add("Nivel de glucosa");

PGrafica.removeAll();
PGrafica.setLayout(new java.awt.BorderLayout());
chart = new GraficaXY("Últimas 15 mediciones de glucosa",
        "Fecha", "Nivel de Glucosa", series, datos);
PGrafica.add(chart.chartPanel, java.awt.BorderLayout.CENTER);
PGrafica.updateUI();

cnx.entablar(query, TQuery, 60, 40);
        
    }//GEN-LAST:event_jButton1ActionPerformed

